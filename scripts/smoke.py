"""Click-through test of the main flows.
Usage: python3 scripts/smoke.py <demo-build-url> [<production-build-url>]
  demo build: VITE_ENABLE_DEMO=true npm run build -- --outDir dist-demo   (needed for the focus -> recap check)
  production build: npm run build   (used to prove the demo controls are absent)"""
import sys, tempfile, os
from PIL import Image
from playwright.sync_api import sync_playwright
B=sys.argv[1] if len(sys.argv)>1 else 'http://localhost:4173'; PROD=sys.argv[2] if len(sys.argv)>2 else None; res=[]
PHOTO=os.path.join(tempfile.gettempdir(),'sr-photo.png'); Image.new('RGB',(600,400),(200,80,60)).save(PHOTO)
def check(name, cond): res.append(('PASS' if cond else 'FAIL', name))
with sync_playwright() as p:
    b=p.chromium.launch(args=['--use-fake-device-for-media-stream','--use-fake-ui-for-media-stream'])
    ctx=b.new_context(viewport={'width':1440,'height':900},permissions=['camera']); pg=ctx.new_page(); errs=[]
    pg.on('pageerror',lambda e: errs.append(str(e)[:100]))
    pg.goto(B+'/friends'); pg.wait_for_timeout(400)
    n0=int(pg.get_by_role('tab',name='Friends').inner_text().split()[-1])
    pg.get_by_role('tab',name='Requests').click(); pg.get_by_role('button',name='Accept').first.click(); pg.wait_for_timeout(500)
    pg.get_by_role('tab',name='Friends').click(); pg.wait_for_timeout(300)
    check('friends: accept request adds a friend', int(pg.get_by_role('tab',name='Friends').inner_text().split()[-1])==n0+1)
    pg.get_by_role('tab',name='Find people').click(); pg.get_by_label('Search people').fill('vih'); pg.wait_for_timeout(700)
    pg.get_by_role('button',name='Add').first.click(); pg.wait_for_timeout(500)
    check('friends: send request shows "Request sent"', 'Request sent' in pg.inner_text('body'))
    pg.goto(B+'/materials'); pg.get_by_role('button',name='Add material').first.click()
    pg.get_by_label('Link').fill('https://www.youtube.com/watch?v=abc'); pg.get_by_role('dialog').get_by_role('button',name='Add',exact=True).click(); pg.wait_for_timeout(600)
    check('materials: added link is listed', 'youtube.com' in pg.inner_text('body'))
    pg.goto(B+'/settings'); pg.wait_for_timeout(300)
    pg.set_input_files('input[aria-label="Upload profile photo"]',PHOTO); pg.wait_for_timeout(900)
    check('settings: profile photo shows in the rail', pg.locator('nav img').count()>=1)
    pg.goto(B+'/focus'); pg.get_by_role('button',name='Use last plan').click(); pg.get_by_role('button',name='Next').click()
    pg.get_by_label('Or type minutes').fill('5'); pg.get_by_role('button',name='Next').click(); pg.wait_for_timeout(900)
    pg.get_by_role('button',name='Start focus session').click(); pg.wait_for_timeout(500)
    pg.goto(B+'/focus/session?demo=1'); pg.wait_for_timeout(400)
    pg.get_by_role('button',name='120×').click(); pg.wait_for_timeout(4500)
    check('focus: session finishes and opens the recap', '/recap/' in pg.url and 'What counted' in pg.inner_text('body'))
    pg.goto(B+'/j/DSA-482'); pg.wait_for_timeout(400)
    pg.get_by_role('button',name='Join room').click(); pg.wait_for_timeout(700)
    check('join: opens the live room', '/room/DSA-482' in pg.url)
    pg.get_by_role('textbox', name='Chat message').fill('hello team'); pg.get_by_role('button',name='Send').click(); pg.wait_for_timeout(500)
    check('room: chat message appears', 'hello team' in pg.inner_text('body'))
    pg.get_by_role('textbox', name='Chat message').fill('/gallery'); pg.get_by_role('button',name='Send').click(); pg.wait_for_timeout(500)
    tiles=pg.locator('section[aria-label="Main view"] button[aria-label]').count()
    check(f'room: /gallery shows 20 tiles on desktop (found {tiles})', tiles==20)
    pg.get_by_role('textbox', name='Chat message').fill('/music https://youtu.be/abc123'); pg.get_by_role('button',name='Send').click(); pg.wait_for_timeout(500)
    check('room: /music starts the hidden player', pg.locator('iframe[title="Study music player"]').count()==1)
    ctx.close()

    # --- Phase 2 fixes ---
    ctx2=b.new_context(viewport={'width':1440,'height':900}); q=ctx2.new_page()
    q.goto(B+'/settings'); q.wait_for_timeout(700)
    check('settings: name and handle are prefilled on direct load', q.get_by_label('Display name').input_value()=='Aarav Kumar' and q.get_by_label('Handle').input_value()=='aarav.k')
    q.goto(B+'/add/vihaan.reddy'); q.wait_for_timeout(600)
    check('invite link /add/<handle> lands on the profile', '/u/vihaan.reddy' in q.url and 'Add friend' in q.inner_text('body'))
    q.get_by_role('button',name='Add friend').click(); q.wait_for_timeout(500)
    check('profile: add friend then shows Cancel request', 'Cancel request' in q.inner_text('body'))
    q.goto(B+'/u/nobody.here'); q.wait_for_timeout(500)
    check('unknown profile shows a clear empty state', 'No such user' in q.inner_text('body'))
    q.goto(B+'/room/ZZZ-999'); q.wait_for_timeout(700)
    check('nonexistent room code is redirected to the join screen with a reason', '/j/ZZZ-999' in q.url and 'Room not found' in q.inner_text('body'))
    q.goto(B+'/room/DSA-482'); q.wait_for_timeout(600)
    vis=q.evaluate("""()=>{const t=document.querySelector('aside [role=tablist]');const r=t.getBoundingClientRect();return [...t.querySelectorAll('[role=tab]')].every(e=>e.getBoundingClientRect().right<=r.right+1)}""")
    check('room: every side-panel tab is visible without scrolling', vis)
    q.goto(B+'/'); q.wait_for_timeout(400)
    check('prototype notice is shown while data is mock', 'Prototype data' in q.inner_text('body'))
    if PROD:
        q.goto(PROD+'/focus/session?demo=1'); q.wait_for_timeout(400)
        check('production build ignores ?demo=1 (no demo bar, redirects to setup)', '/focus' in q.url and 'Demo' not in q.inner_text('body'))
    ctx2.close()
    ctx=b.new_context(viewport={'width':390,'height':844},has_touch=True,is_mobile=True); pg=ctx.new_page()
    pg.on('pageerror',lambda e: errs.append(str(e)[:100]))
    pg.goto(B+'/room/DSA-482'); pg.wait_for_timeout(600)
    pg.get_by_role('button',name='Change layout').click(); pg.wait_for_timeout(300)
    check('phone: gallery page 1/4', '1 / 4' in pg.inner_text('body'))
    pg.get_by_role('button',name='Next page').click(); pg.wait_for_timeout(1200)
    check('phone: next page works', '2 / 4' in pg.inner_text('body'))
    pg.get_by_role('button',name='More').click(); pg.get_by_role('button',name='Doubts').click(); pg.wait_for_timeout(500)
    pg.get_by_label('Ask a doubt').fill('What is amortized O(1)?'); pg.get_by_role('button',name='Post doubt').click(); pg.wait_for_timeout(600)
    check('phone: doubt posted from the sheet', 'amortized' in pg.inner_text('body'))
    ctx.close(); b.close()
for r in res: print(*r)
print('page errors:', errs)
